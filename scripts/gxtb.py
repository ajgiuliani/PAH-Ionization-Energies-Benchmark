    def read_results(self):
        """ results are read from PREFIX.out file
            It will be destroyed after it is read to avoid
            reading it once again after some runtime error """

        with open(os.path.join(self.directory, f'{self.prefix}.out')) as fd:
            self.lines = fd.readlines()

        self.atoms = self.atoms_input
        #print("positions:", self.atoms.get_positions())
        
        #charges, energy, dipole = self.read_charges_energy_dipole()
        energy = self.read_energy()
        charges, dipole = self.read_charges_dipole()
        if charges is not None:
            self.results['charges'] = charges
        self.results['energy'] = energy
        #print("energy: ", energy,"\n")
        if dipole is not None:
            self.results['dipole'] = dipole
        if self.do_forces:
            forces = self.read_forces()
            self.results['forces'] = forces
        self.mmpositions = None

        # calculation was carried out with atoms written in coord file

        
    def read_forces(self):
        """Read Forces from the gradient file."""
        from ase.units import Bohr, Hartree

        with open(os.path.join(self.directory, 'gradient'), 'r') as fd:
            lines = fd.readlines()

        # Initialiser l'index pour les gradients
        gradients = []

        for iline, line in enumerate(lines):
            if line.startswith('$grad'):
                for line in lines[iline+1:]:
                    if any(c.isalpha() for c in line.split()):
                        continue
                    words = line.split()
                    if words:
                        try:
                            row_values = [float(word.replace('D', 'E')) for word in words[:3]]
                            if row_values:
                                row_values[row_values == 0.0] =  eps
                                gradients.append(row_values)
                        except ValueError:
                            pass
                break
        return -np.array(gradients) * Hartree / Bohr

    def read_energy(self):
        """Get partial charges on atoms
            in case we cannot find charges they are set to None
        """
        with open(os.path.join(self.directory, 'energy')) as fd:
            lines = fd.readlines()

        for iline, line in enumerate(lines):
            if line.startswith('$energy'):
                # La ligne après "$energy" contient les valeurs d'énergie
                if iline + 1 < len(lines):
                    # Lire la ligne suivante
                    energy_line = lines[iline+1]
                    # Extraire les valeurs numériques de cette ligne
                    values = energy_line.split()
                    if len(values) >= 2:  # S'assurer qu'il y a au moins deux valeurs
                        energy = float(values[1]) * Hartree # Prendre la deuxième valeur
                        #energy = float(values[1]) # Prendre la deuxième valeur
                        break  # On peut sortir une fois la valeur d'énergie trouvée
                        
        return energy

