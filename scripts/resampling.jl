#!/usr/bin/env julia
# =====================================================================
# resampling.jl
#
# Resolution of the benchmark metrics: how far the MAE and RMSE of each
# method are determined, given (i) the finite number of reference
# molecules and (ii) the quoted experimental uncertainties of the
# reference values. This quantifies the reviewer's concern that small
# differences in MAE/RMSE may not be significant on sets of 5-7
# molecules.
#
# It reuses the data, the ionization-energy definitions and the metric
# functions of analysis.jl (included below); nothing is duplicated. The
# per-molecule signed errors it works on are exactly errors(method,
# which) of that file, and the uncertainties are uncertainties(which).
#
# Three estimates are produced for every method and ionization order,
# as 95% half-widths on the MAE (eV):
#
#   (A) experimental only : the reference values e_i are resampled from
#       N(e_i, u_i^2), the CALCULATED values are held fixed, and the
#       metric is recomputed. Isolates the effect of the reference data.
#
#   (B) sample size only  : the n molecules are resampled with
#       replacement (bootstrap) and the metric recomputed. Isolates the
#       effect of the finite set.
#
#   (C) both combined     : the two sources being independent, their
#       half-widths are added in quadrature, C = sqrt(A^2 + B^2).
#       No further resampling is involved.
#
# The analytic standard error SE(MAE) = s / sqrt(n), s the sample SD of
# the absolute errors, is also listed as a check on (B).
#
# Usage (from the repository root):
#
#     julia scripts/resampling.jl
#
# Output:
#     output/tableS7_resolution.tex   summary rows (median over methods)
#     output/resolution_full.txt      per-method detail, all three estimates
#     output/tableS8_combined.tex     per-method MAE and its three 95% half-widths
#   and a summary is printed to the terminal.
#
# The Monte-Carlo is seeded, so the numbers are reproducible; they are
# stable to 0.01 eV between runs and against the seed.
#
# Dependencies: those of analysis.jl, plus Random (standard library).
# Licence: MIT (see scripts/LICENSE). The data are CC BY 4.0.
# =====================================================================

using Random, Statistics, Printf

# Pull in the benchmark set, the raw energies, the ionization-energy
# definitions and the metric helpers. The include does not run
# analysis.jl's main(): that call is guarded by a PROGRAM_FILE check.
include(joinpath(@__DIR__, "analysis.jl"))

Random.seed!(20260923)
const NB = 200_000                       # Monte-Carlo / bootstrap resamplings

# 95% interval half-width of a Monte-Carlo sample.
halfwidth95(s) = (quantile(s, 0.975) - quantile(s, 0.025)) / 2

# ---------------------------------------------------------------------
# Resampling estimators, acting directly on the signed errors d = calc - exp.
# Perturbing a reference e_i -> e_i + delta gives a new error d_i - delta;
# since |.| is symmetric and delta ~ N(0, u_i^2), adding u_i*randn is
# equivalent and avoids re-touching the calculated values.
# ---------------------------------------------------------------------
maevec(v) = sum(abs, v) / length(v)

function resolution(d::Vector{Float64}, u::Vector{Float64})
    n = length(d)
    aA = Vector{Float64}(undef, NB)      # (A) experimental only
    aB = Vector{Float64}(undef, NB)      # (B) sample size only
    buf = Vector{Float64}(undef, n)
    for k in 1:NB
        # (A) references perturbed, molecules fixed
        @inbounds for i in 1:n
            buf[i] = d[i] + u[i] * randn()
        end
        aA[k] = maevec(buf)
        # (B) molecules resampled with replacement
        @inbounds for i in 1:n
            buf[i] = d[rand(1:n)]
        end
        aB[k] = maevec(buf)
    end
    A = halfwidth95(aA)
    B = halfwidth95(aB)
    # (C) independent sources: half-widths added in quadrature
    return (A = A, B = B, C = hypot(A, B))
end

# Standard error of the MAE, s/sqrt(n).
se_mae(d) = std(abs.(d)) / sqrt(length(d))     # std: sample SD (ddof = 1)

# Method labels as in the SI tables.
texname(m) = m == "WB97X-3C" ? "\$\\omega\$B97X-3C" : m

# ---------------------------------------------------------------------
# Run and report
# ---------------------------------------------------------------------
const CASES = ((:first, "IE1"), (:second, "IE2"), (:double, "IEd"))

function main()
    full  = joinpath(OUT, "resolution_full.txt")
    summ  = joinpath(OUT, "tableS7_resolution.tex")

    summary = Dict{Symbol,NamedTuple}()
    permethod = Dict{Tuple{Symbol,String},NTuple{4,Float64}}()   # (MAE, B, A, C)

    open(full, "w") do io
        println(io, "# Resolution of the benchmark metrics (95% half-widths on MAE, eV)")
        println(io, "# Generated by scripts/resampling.jl, NB = ", NB, " resamplings, seed 20260923.")
        println(io, "# A = experimental only, B = sample size only, C = sqrt(A^2 + B^2).")
        for (which, label) in CASES
            u = uncertainties(which)
            n = length(u)
            println(io, "\n## ", label, "  (n = ", n, ")   uncertainties (eV): ", u)
            @printf(io, "%-11s %7s %7s %8s | %8s %8s %8s\n",
                    "method", "MAE", "RMSE", "SE(MAE)", "A_exp", "B_size", "C_both")
            As = Float64[]; Bs = Float64[]; Cs = Float64[]
            for m in METHODS
                d = errors(m, which)
                r = resolution(d, u)
                push!(As, r.A); push!(Bs, r.B); push!(Cs, r.C)
                permethod[(which, m)] = (maevec(d), r.B, r.A, r.C)
                @printf(io, "%-11s %7.2f %7.2f %8.2f | %8.2f %8.2f %8.2f\n",
                        pretty(m), maevec(d), sqrt(mean(d .^ 2)), se_mae(d),
                        r.A, r.B, r.C)
            end
            summary[which] = (n = n, A = median(As), B = median(Bs),
                              C = median(Cs))
        end
    end

    # SI per-method table: MAE and its three 95% half-widths, one block per
    # ionization order (same layout as Table S3).
    open(joinpath(OUT, "tableS8_combined.tex"), "w") do io
        println(io, "% Table S8 - MAE and its 95% half-widths (eV) from the sample size alone,")
        println(io, "% the experimental uncertainties alone, and both combined.")
        println(io, "% Columns: Methods & MAE & Sample size & Experimental & Combined")
        println(io, "% Generated by scripts/resampling.jl.")
        for (which, label) in CASES
            @printf(io, "\\hline\n%s (\$n = %d\$) & & & & \\\\\n\\hline\n",
                    label == "IEd" ? "IE double" : label, length(uncertainties(which)))
            for m in METHODS
                mae_, b, a, c = permethod[(which, m)]
                @printf(io, "  %s & %.2f & %.2f & %.2f & %.2f \\\\\n",
                        texname(m), mae_, b, a, c)
            end
        end
    end

    # SI summary table: rows and numbers only, to match the other output/*.tex.
    open(summ, "w") do io
        println(io, "% Table S7 - resolution of the metrics, 95% half-widths on MAE (eV),")
        println(io, "% median over the thirteen methods. Columns:")
        println(io, "%   Sample size (bootstrap) & Experimental (MC) & Combined")
        println(io, "% Generated by scripts/resampling.jl.")
        for (which, label) in CASES
            s = summary[which]
            @printf(io, "%s (\$n = %d\$) & %.2f & %.2f & %.2f \\\\\n",
                    label == "IEd" ? "IE double" : label, s.n, s.B, s.A, s.C)
        end
    end

    # Terminal summary.
    println("\nResolution of the metrics (95% half-widths on MAE, eV; median over methods)")
    @printf("%-14s %10s %12s %10s\n", "", "size (B)", "exp (A)", "both (C)")
    for (which, label) in CASES
        s = summary[which]
        @printf("%-14s %10.2f %12.2f %10.2f\n",
                "$label (n=$(s.n))", s.B, s.A, s.C)
    end
    println("\nWritten to ", OUT, " :\n  resolution_full.txt\n  tableS7_resolution.tex\n  tableS8_combined.tex")
end

if abspath(PROGRAM_FILE) == @__FILE__
    main()
end
